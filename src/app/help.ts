// 화면마다 맨 아래에 보여 주는 간단한 사용법. 주소(#/탭/…)로 어느 화면인지 고른다.
// 새 화면을 만들면 여기에 몇 줄 추가하면 된다. 한 화면에 3~5줄, 폰에서 한눈에 읽히게.

export interface Help {
  title: string;
  lines: string[];
}

const H = (title: string, ...lines: string[]): Help => ({ title, lines });

export function helpFor(tabId: string, params: string[]): Help | null {
  const [p0, p1, p2] = params;
  switch (tabId) {
    case 'home':
      return H(
        '할 일',
        '날짜를 누르고 할 일을 적은 뒤 엔터 → 계속 이어서 적을 수 있어요.',
        '네모를 누르면 완료(아래로), ☆을 누르면 중요(위로). 글자를 누르면 바로 고쳐요.',
        '길게 누르면 삭제하거나 다른 날로 옮겨요. 지난 날 못 한 일은 [오늘로 옮기기].',
        '위의 [월]·[주]·[일]·[목록]으로 보기를 바꿔요. 원장님·선생님이 같은 목록을 함께 봐요.',
      );

    case 'briefing':
      if (p0 === 'texts')
        return H(
          '문구 관리',
          '위에서 단계를 고르면 그 단계 수업 코드(예: P1-1)별 문구가 보여요.',
          '"비어 있음"을 누르면 문구를 적을 수 있어요. 아이 이름은 넣지 않아요.',
          '엑셀에 정리한 문구는 [일괄 가져오기]로 한 번에 넣어요.',
          '베이직 반은 코드가 없어서 날짜별 수업 계획으로 적어요.',
        );
      return H(
        '수업 후 브리핑',
        '날짜를 고르고, 위의 시간 버튼으로 반을 골라요(숫자 = 보낸 아이/보낼 아이).',
        '아이 옆 [보내기]를 누르면 문구가 복사되고 카톡 공유가 열려요.',
        '결석한 아이는 빠져요. 보강 온 아이는 [+ 아이 추가].',
        '오늘 문구를 고치려면 [문구 수정], 문구 모음은 위의 [문구 관리].',
      );

    case 'roster':
      return rosterHelp(p0, p1, p2);

    case 'plan':
      return H(
        '수업 달력',
        '칸 아래 색 띠가 그날의 진도(예: 2주, 12월 1주)예요.',
        '날짜를 누르면 휴강(이후 수업이 뒤로 밀림)·진도 직접 지정·행사 메모·출석.',
        '방학·연수는 [휴원 기간 추가]. 학부모님께 안내했으면 [이 달 확정].',
        '하늘색은 체험, 분홍색은 보강 예약이에요(안내 달력 이미지엔 안 들어가요).',
      );

    case 'makeup':
      return H(
        '토요 보강데이',
        '위는 보강데이별 30분 타임, 아래는 이 달 결석했는데 예약 안 된 "미정" 학생이에요.',
        '미정 학생을 누르고 빈 타임을 고르면 예약돼요.',
        '예약된 타임을 누르면 [다른 시간으로 옮기기]·[예약 취소]·[학생 카드 보기].',
      );

    case 'export':
      return H(
        '안내 달력 만들기',
        '기간(두 달)을 고르면 학부모 안내용 달력 미리보기가 나와요.',
        '강조 안내·하단 문구를 고치고 모양(나란히·위아래, 1:1·4:5)을 골라요.',
        '이미지를 저장·공유하면 기록이 남아요.',
        '보내기 전에 수업 달력에서 그 달을 [확정]해 두세요.',
      );

    case 'attend':
      if (p1)
        return H(
          '반 출석',
          '기본은 전원 출석이에요. 결석한 아이만 눌러 주세요(다시 누르면 출석).',
          '결석이 없으면 [확인 완료]를 눌러요. 결석을 누르면 저절로 완료돼요.',
          '체험 온 아이는 [이 반에 체험수업 기록].',
        );
      return H(
        '출석',
        '그날 수업하는 반 목록이에요. 반을 눌러 출석을 체크해요.',
        '✓는 출석 확인을 마친 반이에요.',
        '◀ ▶로 날짜를 옮기고, [오늘로]로 돌아와요.',
      );

    case 'settings':
      return H(
        '설정',
        '운영 시간·선호 시간대는 편성과 빈자리(새 반 시간)에 쓰여요.',
        '할 일 관리: 자동 할 일 켜기/끄기, 반복 할 일 추가·수정·순서 변경.',
        '한 달에 한 번 [백업 내보내기]로 파일을 저장해 두세요.',
        '휴원일·공휴일을 바꾸면 수업 날짜가 다시 계산돼요.',
      );
  }
  return null;
}

function rosterHelp(view = 'classes', id?: string, rest?: string): Help | null {
  if (view === 'sim-compare')
    return H('시안 비교', '두 시안을 고르면 반 수·학생 수·빈자리·경고를 나란히 비교해요.', '마음에 드는 시안을 열어 이어서 고쳐요.');
  if (view === 'sim' && id && rest === 'apply')
    return H(
      '시안 적용',
      '적용하면 실제 반·배정이 시안대로 바뀌어요. 먼저 [백업 내보내기]를 해 두세요.',
      '언제부터 바뀔지(○월 진도 기준 또는 날짜)를 고르고 미리보기를 확인해요.',
      '퇴원 예정 아이는 체크한 아이만 퇴원 처리돼요.',
    );
  if (view === 'sim' && id)
    return H(
      '시안 고치기',
      '반을 톡 누르고 초록 칸을 누르면 그 시간으로 옮겨져요(PC는 끌어도 돼요).',
      '반을 다른 반 위에 놓으면 합치기, [빼놓은 반]에 놓으면 시간표에서 빠져요.',
      '고른 반을 한 번 더 누르면(PC는 더블클릭) 반 상세: 아이별 유지·이동·퇴원 예정 표시.',
      '오른쪽(폰은 아래) 경고·변경 목록을 확인하고, 다 되면 [적용하기].',
    );
  if (view === 'sim')
    return H(
      '반 편성 시안',
      '[새 시안]을 만들면 지금 시간표가 복사돼요. 여기서 고쳐도 실제 반은 그대로예요.',
      '시안을 눌러 고치고, 두 시안은 [두 시안 비교]로 나란히 볼 수 있어요.',
      '다 되면 시안 안에서 [적용하기] → 백업 → 미리보기 확인 후 적용.',
    );
  if (view === 'vacancy')
    return H(
      '빈자리',
      '학년(또는 출생연도)과 기준일을 고르세요. [3월 새 학기]면 학년이 한 단계 올라요.',
      'A는 기존 반의 남은 자리(곧 생길 자리 날짜 포함), B는 새 반을 열 수 있는 시간.',
      '"대기 n명"을 누르면 그 시간에 맞는 대기자 목록이 나와요.',
      '칸을 고르고 아래 [대기자로 등록]·[체험 예약]을 누르면 값이 채워져요.',
    );
  if (view === 'waitlist' && id === 'class')
    return H('반에 맞는 대기자', '이 반 학년·희망 시간에 맞는 대기자예요. 눌러서 연락하거나 체험을 잡아요.');
  if (view === 'waitlist' && id)
    return H(
      '대기자',
      '진행 단계 버튼으로 문의 → 체험 예약 → 체험 완료 → 포기를 바꿔요.',
      '[체험수업 기록]으로 체험 날짜를 잡고, [등록하기]를 누르면 학생으로 옮겨져요.',
      '희망 요일·시간과 희망 시작 시기를 넣으면 빈자리에서 자동으로 찾아 줘요.',
    );
  if (view === 'waitlist')
    return H(
      '대기자',
      '[대기자 추가]로 문의한 아이를 적어요(학년·희망 시간·희망 시작 시기).',
      '단계별(문의·체험 예약·체험 완료)로 모여 보여요. 눌러서 자세히 봐요.',
      '연락할 일은 할 일 탭 달력에 적어 두면 잊지 않아요.',
    );
  if (view === 'student' && id)
    return H(
      '학생 카드',
      '맨 위 📌는 특이사항이에요. [정보 수정]으로 연락처·가능 시간을 고쳐요.',
      '[반 이동]으로 반을 바꾸고, 휴원·퇴원은 [정보 수정]에서 바꿔요(기록은 남아요).',
      '상담은 [+ 기록]으로 남기고, "다음 연락일"도 적어 둘 수 있어요.',
    );
  if (view === 'students')
    return H(
      '학생',
      '이름(초성도 돼요: ㄱㅅㅇ)으로 찾고, 상태·요일·학년으로 걸러 봐요.',
      '"확인 필요"는 정보가 비었거나 다시 볼 학생이에요.',
      '여러 명은 [붙여넣기로 가져오기]로 한 번에 넣어요.',
    );
  if (view === 'class' && id)
    return H(
      '반 상세',
      '명단에서 학생 추가·이동·빼기를 해요. 앞으로 올 학생은 따로 보여요.',
      '진도 기준점("이 달에 이 단계 몇 단원")을 넣으면 매달 저절로 올라가요.',
      '[수정]으로 시간·학년을 바꾸고, 운영을 끝내면 폐반해요.',
    );
  if (view === 'progress-import') return H('진도 일괄 입력', '엑셀에서 표를 복사해 붙여넣으면 반별 진도 기준점이 한 번에 들어가요.');
  return H(
    '시간표',
    '이름을 누르면 정보 수정·반 이동·학생 카드, 반 머리를 누르면 반 상세.',
    '빈 곳을 누르면 그 요일·시간에 새 반을 만들어요.',
    '흐린 +이름은 적용일이 아직 안 된(들어올 예정인) 학생이에요.',
    '[목록]으로 바꾸면 요일별 반 인원·경고를 자세히 봐요.',
  );
}
